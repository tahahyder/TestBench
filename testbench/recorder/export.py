"""Export supported web YAML tests as pytest-playwright Page Object code."""

import keyword
import re
from pathlib import Path
from typing import Any

from testbench.core.runner import load_test


def export_pytest_playwright(test_path: Path) -> str:
    """Return a readable pytest-playwright module for one supported web test."""
    spec = load_test(test_path)
    if spec.target != "web":
        raise ValueError(f"pytest-playwright export is not supported for target {spec.target!r} yet.")
    unsupported = sorted({step.action for step in spec.steps if step.action not in _SUPPORTED_ACTIONS})
    if unsupported:
        raise ValueError("pytest-playwright export does not support these steps: " + ", ".join(unsupported))

    lines = [
        '"""Generated by TestBench; install pytest-playwright to run this test."""',
        "",
        "import os",
        "import re",
        "",
        "",
        "class RecordedPage:",
        "    def __init__(self, page):",
        "        self.page = page",
        "",
        "    def locator(self, target):",
        "        if isinstance(target, str):",
        "            return self.page.get_by_text(target, exact=True)",
        "        kind, value = next(iter(target.items()))",
        "        if kind == 'role':",
        "            return self.page.get_by_role(value['role'], name=value['name'], exact=True)",
        "        if kind == 'label':",
        "            return self.page.get_by_label(value, exact=True)",
        "        if kind == 'placeholder':",
        "            return self.page.get_by_placeholder(value, exact=True)",
        "        if kind == 'text':",
        "            return self.page.get_by_text(value, exact=True)",
        "        if kind == 'test_id':",
        "            return self.page.get_by_test_id(value)",
        "        if kind == 'id':",
        "            return self.page.locator('#' + value)",
        "        if kind == 'css':",
        "            return self.page.locator(value)",
        "        if kind == 'xpath':",
        "            return self.page.locator('xpath=' + value)",
        "        raise ValueError(f'Unsupported recorded locator: {kind}')",
        "",
        "def _resolve(value):",
        "    if not isinstance(value, str):",
        "        return value",
        "    for name in re.findall(r'\\$\\{([A-Za-z_][A-Za-z0-9_]*)\\}', value):",
        "        replacement = os.environ.get(name)",
        "        if replacement is None:",
        "            raise RuntimeError(f'Missing required environment variable: {name}')",
        "        value = value.replace('${' + name + '}', replacement)",
        "    return value",
        "",
        f"def test_{_safe_name(spec.name)}(page):",
        "    flow = RecordedPage(page)",
    ]
    for index, step in enumerate(spec.steps, start=1):
        lines.extend(_render_step(step.action, step.value, index))
    lines.extend(["", ""])
    return "\n".join(lines)


def write_pytest_playwright(test_path: Path, destination: Path | None = None) -> Path:
    """Write an exported module next to the source YAML unless overridden."""
    source = Path(test_path)
    output = destination or source.with_name(f"{source.stem}_playwright.py")
    output.write_text(export_pytest_playwright(source), encoding="utf-8")
    return output


def _render_step(action: str, value: Any, index: int) -> list[str]:
    if action == "open":
        return [f"    page.goto({_literal(value)})"]
    if action == "click":
        body = f"flow.locator({_literal(value)}).click()"
    elif action == "type":
        field = value["field"]
        text = value["value"]
        body = f"flow.locator({_literal(field)}).fill(_resolve({_literal(text)}))"
    elif action == "expect_visible":
        body = f"assert flow.locator({_literal(value)}).is_visible()"
    elif action == "expect_text":
        body = f"assert {_literal(value)} in page.locator('body').inner_text()"
    elif action == "wait":
        body = f"page.wait_for_timeout({round(float(value) * 1000)})"
    elif action == "screenshot":
        body = f"page.screenshot(path={_literal(f'{index:03d}_{value}.png')})"
    elif action == "select_option":
        body = f"flow.locator({_literal(value['field'])}).select_option(label=_resolve({_literal(value['value'])}))"
    elif action == "scroll":
        amount = int(value["amount"])
        direction = -amount if value["direction"] in {"up", "left"} else amount
        x, y = (direction, 0) if value["direction"] in {"left", "right"} else (0, direction)
        body = f"page.mouse.wheel({x}, {y})"
    elif action == "expect_url_contains":
        body = f"assert {_literal(value)} in page.url"
    elif action == "expect_enabled":
        body = (
            f"assert flow.locator({_literal(value['target'])}).is_enabled() "
            if value["enabled"]
            else f"assert not flow.locator({_literal(value['target'])}).is_enabled()"
        )
    else:
        raise ValueError(f"Unsupported pytest-playwright action: {action}")
    return [f"    {body}"]


def _literal(value: Any) -> str:
    return repr(value)


def _safe_name(value: str) -> str:
    normalized = re.sub(r"\W+", "_", value).strip("_").lower() or "recorded_test"
    if normalized[0].isdigit() or keyword.iskeyword(normalized):
        normalized = f"recorded_{normalized}"
    return normalized


_SUPPORTED_ACTIONS = {
    "open",
    "click",
    "type",
    "expect_visible",
    "expect_text",
    "wait",
    "screenshot",
    "select_option",
    "scroll",
    "expect_url_contains",
    "expect_enabled",
}
